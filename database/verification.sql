
-- ==========================================
-- TRANSERA DATABASE VERIFICATION
-- ==========================================

SET LINESIZE 200
SET PAGESIZE 100

COLUMN PROCESS_ID FORMAT A12
COLUMN OPERATION_ID FORMAT A15
COLUMN PROCESS_STATE FORMAT A22
COLUMN BUSINESS_STATUS FORMAT A20

PROMPT === BUSINESS OPERATIONS ===

SELECT OPERATION_ID, BUSINESS_STATUS
FROM BUSINESS_OPERATIONS
ORDER BY OPERATION_ID;

PROMPT === PROCESSES ===

SELECT PROCESS_ID,
       OPERATION_ID,
       PROCESS_STATE,
       ARRIVAL_TIME,
       BURST_TIME,
       PRIORITY
FROM PROCESSES
ORDER BY PROCESS_ID;

PROMPT === RESOURCE AVAILABILITY ===

SELECT *
FROM RESOURCES;

PROMPT === RESOURCE ALLOCATIONS ===

SELECT *
FROM RESOURCE_ALLOCATIONS;

PROMPT === PROCESS STATE SUMMARY ===

SELECT PROCESS_STATE, COUNT(*) AS TOTAL
FROM PROCESSES
GROUP BY PROCESS_STATE;

PROMPT === BUSINESS STATUS SUMMARY ===

SELECT BUSINESS_STATUS, COUNT(*) AS TOTAL
FROM BUSINESS_OPERATIONS
GROUP BY BUSINESS_STATUS;
