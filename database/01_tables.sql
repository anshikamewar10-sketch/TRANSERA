CREATE TABLE USERS (
    USER_ID VARCHAR2(10),
    USERNAME VARCHAR2(30) NOT NULL,
    PASSWORD VARCHAR2(100) NOT NULL,
    FULL_NAME VARCHAR2(50) NOT NULL,
    DEPARTMENT VARCHAR2(30) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(15) DEFAULT 'ACTIVE',
    PRIMARY KEY (USER_ID),
    UNIQUE (USERNAME)
);

CREATE TABLE INVENTORY (
    PRODUCT_ID VARCHAR2(10),
    PRODUCT_NAME VARCHAR2(50) NOT NULL,
    CATEGORY VARCHAR2(30) NOT NULL,
    QUANTITY NUMBER NOT NULL,
    UNIT_PRICE NUMBER(10,2) NOT NULL,
    REORDER_LEVEL NUMBER NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE BUSINESS_OPERATIONS (
    OPERATION_ID VARCHAR2(10),
    USER_ID VARCHAR2(10) NOT NULL,
    PRODUCT_ID VARCHAR2(10) NOT NULL,
    OPERATION_TYPE VARCHAR2(50) NOT NULL,
    DESCRIPTION VARCHAR2(200),
    DEPARTMENT VARCHAR2(30) NOT NULL,
    OPERATION_QUANTITY NUMBER NOT NULL,
    OPERATION_MODE VARCHAR2(15) NOT NULL,
    PRIORITY VARCHAR2(10) NOT NULL,
    BUSINESS_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (OPERATION_ID),
    CONSTRAINT FK_OPERATION_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

CREATE TABLE PROCESSES (
    PROCESS_ID VARCHAR2(10),
    OPERATION_ID VARCHAR2(10) NOT NULL,
    PROCESS_STATE VARCHAR2(20) DEFAULT 'READY',
    ARRIVAL_TIME NUMBER NOT NULL,
    BURST_TIME NUMBER NOT NULL,
    PRIORITY NUMBER NOT NULL,
    ALGORITHM_USED VARCHAR2(20),
    COMPLETION_TIME NUMBER,
    PRIMARY KEY (PROCESS_ID)
);

CREATE TABLE RESOURCES (
    RESOURCE_ID VARCHAR2(10),
    RESOURCE_NAME VARCHAR2(50) NOT NULL,
    RESOURCE_TYPE VARCHAR2(30) NOT NULL,
    TOTAL_UNITS NUMBER NOT NULL,
    AVAILABLE_UNITS NUMBER NOT NULL,
    RESOURCE_STATUS VARCHAR2(20) DEFAULT 'AVAILABLE',
    PRIMARY KEY (RESOURCE_ID)
);

CREATE TABLE RESOURCE_ALLOCATIONS (
    ALLOCATION_ID VARCHAR2(10),
    PROCESS_ID VARCHAR2(10) NOT NULL,
    RESOURCE_ID VARCHAR2(10) NOT NULL,
    ALLOCATED_UNITS NUMBER DEFAULT 1 NOT NULL,
    ALLOCATION_STATUS VARCHAR2(20) DEFAULT 'ALLOCATED' NOT NULL,
    ALLOCATION_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ALLOCATION_ID),
    CONSTRAINT FK_RA_PROCESS FOREIGN KEY (PROCESS_ID) REFERENCES PROCESSES(PROCESS_ID),
    CONSTRAINT FK_RA_RESOURCE FOREIGN KEY (RESOURCE_ID) REFERENCES RESOURCES(RESOURCE_ID)
);

CREATE TABLE SYSTEM_LOGS (
    LOG_ID VARCHAR2(10),
    PROCESS_ID VARCHAR2(10) NOT NULL,
    EVENT_TYPE VARCHAR2(30) NOT NULL,
    DESCRIPTION VARCHAR2(100),
    EVENT_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (LOG_ID),
    CONSTRAINT FK_SYSTEM_PROCESS FOREIGN KEY (PROCESS_ID) REFERENCES PROCESSES(PROCESS_ID)
);

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID VARCHAR2(10),
    PROCESS_ID VARCHAR2(10) NOT NULL,
    OPERATION_ID VARCHAR2(10) NOT NULL,
    TRANSACTION_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    START_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    END_TIME TIMESTAMP(6),
    PRIMARY KEY (TRANSACTION_ID),
    CONSTRAINT FK_TRANS_PROCESS FOREIGN KEY (PROCESS_ID) REFERENCES PROCESSES(PROCESS_ID),
    CONSTRAINT FK_TRANS_OPERATION FOREIGN KEY (OPERATION_ID) REFERENCES BUSINESS_OPERATIONS(OPERATION_ID)
);

CREATE TABLE TRANSACTION_LOGS (
    LOG_ID VARCHAR2(10),
    TRANSACTION_ID VARCHAR2(10) NOT NULL,
    EVENT_TYPE VARCHAR2(30) NOT NULL,
    TABLE_NAME VARCHAR2(30) NOT NULL,
    DESCRIPTION VARCHAR2(100),
    LOG_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (LOG_ID),
    CONSTRAINT FK_LOG_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(TRANSACTION_ID)
);

