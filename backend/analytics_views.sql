
CREATE OR REPLACE VIEW VW_AN_OPERATION_SUMMARY AS
SELECT
    COUNT(*) AS TOTAL_OPERATIONS,
    NVL(SUM(CASE WHEN BUSINESS_STATUS = 'COMPLETED'
        THEN 1 ELSE 0 END), 0) AS COMPLETED_OPERATIONS,
    NVL(SUM(CASE WHEN BUSINESS_STATUS = 'PENDING'
        THEN 1 ELSE 0 END), 0) AS PENDING_OPERATIONS,
    NVL(SUM(CASE WHEN BUSINESS_STATUS = 'PROCESSING'
        THEN 1 ELSE 0 END), 0) AS PROCESSING_OPERATIONS,
    CASE WHEN COUNT(*) = 0 THEN 0
        ELSE ROUND(
            100 * SUM(CASE WHEN BUSINESS_STATUS = 'COMPLETED'
                THEN 1 ELSE 0 END) / COUNT(*), 2
        )
    END AS COMPLETION_PERCENT
FROM BUSINESS_OPERATIONS;

CREATE OR REPLACE VIEW VW_AN_PROCESS_SUMMARY AS
SELECT
    COUNT(*) AS TOTAL_PROCESSES,
    NVL(SUM(CASE WHEN PROCESS_STATE = 'TERMINATED'
        THEN 1 ELSE 0 END), 0) AS TERMINATED_PROCESSES,
    NVL(SUM(CASE WHEN PROCESS_STATE = 'WAITING'
        THEN 1 ELSE 0 END), 0) AS WAITING_PROCESSES,
    NVL(SUM(CASE WHEN PROCESS_STATE = 'ALLOCATED'
        THEN 1 ELSE 0 END), 0) AS ALLOCATED_PROCESSES,
    CASE WHEN COUNT(*) = 0 THEN 0
        ELSE ROUND(
            100 * SUM(CASE WHEN PROCESS_STATE = 'TERMINATED'
                THEN 1 ELSE 0 END) / COUNT(*), 2
        )
    END AS COMPLETION_PERCENT
FROM PROCESSES;

CREATE OR REPLACE VIEW VW_AN_PROCESS_STATES AS
SELECT PROCESS_STATE AS STATUS,
       COUNT(*) AS TOTAL
FROM PROCESSES
GROUP BY PROCESS_STATE;

CREATE OR REPLACE VIEW VW_AN_DEPARTMENT_STATS AS
SELECT
    DEPARTMENT,
    COUNT(*) AS TOTAL_OPERATIONS,
    NVL(SUM(CASE WHEN BUSINESS_STATUS = 'COMPLETED'
        THEN 1 ELSE 0 END), 0) AS COMPLETED_OPERATIONS,
    ROUND(
        100 * NVL(SUM(CASE WHEN BUSINESS_STATUS = 'COMPLETED'
            THEN 1 ELSE 0 END), 0)
        / NULLIF(COUNT(*), 0), 2
    ) AS COMPLETION_PERCENT
FROM BUSINESS_OPERATIONS
GROUP BY DEPARTMENT;

CREATE OR REPLACE VIEW VW_AN_RESOURCE_USAGE AS
SELECT
    R.RESOURCE_ID,
    R.RESOURCE_NAME,
    R.TOTAL_UNITS,
    R.AVAILABLE_UNITS,
    R.TOTAL_UNITS - R.AVAILABLE_UNITS AS USED_UNITS,
    NVL(A.ACTIVE_UNITS, 0) AS RECORDED_ALLOCATIONS,
    ROUND(
        100 * (R.TOTAL_UNITS - R.AVAILABLE_UNITS)
        / NULLIF(R.TOTAL_UNITS, 0), 2
    ) AS UTILIZATION_PERCENT,
    R.TOTAL_UNITS - R.AVAILABLE_UNITS
        - NVL(A.ACTIVE_UNITS, 0) AS ACCOUNTING_DIFFERENCE,
    NVL(Q.WAITING_PROCESSES, 0) AS WAITING_PROCESSES,
    NVL(Q.REQUESTED_UNITS, 0) AS REQUESTED_UNITS,
    NVL(H.HISTORICAL_UNITS, 0) AS HISTORICAL_UNITS
FROM RESOURCES R
LEFT JOIN (
    SELECT RESOURCE_ID,
           SUM(ALLOCATED_UNITS) AS ACTIVE_UNITS
    FROM RESOURCE_ALLOCATIONS
    WHERE ALLOCATION_STATUS = 'ALLOCATED'
    GROUP BY RESOURCE_ID
) A ON A.RESOURCE_ID = R.RESOURCE_ID
LEFT JOIN (
    SELECT RR.RESOURCE_ID,
           COUNT(DISTINCT RR.PROCESS_ID) AS WAITING_PROCESSES,
           SUM(RR.REQUESTED_UNITS) AS REQUESTED_UNITS
    FROM RESOURCE_REQUESTS RR
    JOIN PROCESSES P
      ON P.PROCESS_ID = RR.PROCESS_ID
    WHERE P.PROCESS_STATE = 'WAITING'
    GROUP BY RR.RESOURCE_ID
) Q ON Q.RESOURCE_ID = R.RESOURCE_ID
LEFT JOIN (
    SELECT RESOURCE_ID,
           SUM(ALLOCATED_UNITS) AS HISTORICAL_UNITS
    FROM RESOURCE_ALLOCATIONS
    GROUP BY RESOURCE_ID
) H ON H.RESOURCE_ID = R.RESOURCE_ID;

CREATE OR REPLACE VIEW VW_AN_TRANSACTION_SUMMARY AS
SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    NVL(SUM(CASE WHEN TRANSACTION_STATUS = 'COMMITTED'
        THEN 1 ELSE 0 END), 0) AS COMMITTED_TRANSACTIONS,
    NVL(SUM(CASE WHEN TRANSACTION_STATUS = 'ROLLED_BACK'
        THEN 1 ELSE 0 END), 0) AS ROLLED_BACK_TRANSACTIONS,
    CASE
        WHEN NVL(SUM(CASE
            WHEN TRANSACTION_STATUS IN ('COMMITTED', 'ROLLED_BACK')
            THEN 1 ELSE 0 END), 0) = 0 THEN 0
        ELSE ROUND(
            100 * SUM(CASE WHEN TRANSACTION_STATUS = 'COMMITTED'
                THEN 1 ELSE 0 END)
            / SUM(CASE
                WHEN TRANSACTION_STATUS IN ('COMMITTED', 'ROLLED_BACK')
                THEN 1 ELSE 0 END), 2
        )
    END AS SUCCESS_PERCENT
FROM TRANSACTIONS;

CREATE OR REPLACE VIEW VW_AN_TRANSACTION_STATES AS
SELECT TRANSACTION_STATUS AS STATUS,
       COUNT(*) AS TOTAL
FROM TRANSACTIONS
GROUP BY TRANSACTION_STATUS;

CREATE OR REPLACE VIEW VW_AN_INTEGRITY AS
SELECT
    (SELECT COUNT(*)
     FROM VW_AN_RESOURCE_USAGE
     WHERE ACCOUNTING_DIFFERENCE <> 0
        OR AVAILABLE_UNITS < 0
        OR AVAILABLE_UNITS > TOTAL_UNITS
        OR TOTAL_UNITS < 0) AS RESOURCE_ERRORS,
    (SELECT COUNT(*)
     FROM INVENTORY
     WHERE QUANTITY < 0) AS NEGATIVE_INVENTORY,
    (SELECT COUNT(*)
     FROM PROCESSES P
     LEFT JOIN BUSINESS_OPERATIONS B
       ON P.OPERATION_ID = B.OPERATION_ID
     WHERE P.PROCESS_STATE = 'TERMINATED'
       AND (B.OPERATION_ID IS NULL
            OR NVL(B.BUSINESS_STATUS, 'UNKNOWN') <> 'COMPLETED')
    ) AS PROCESS_OPERATION_ERRORS,
    (SELECT COUNT(*)
     FROM TRANSACTIONS T
     LEFT JOIN PROCESSES P
       ON T.PROCESS_ID = P.PROCESS_ID
     LEFT JOIN BUSINESS_OPERATIONS B
       ON T.OPERATION_ID = B.OPERATION_ID
     WHERE P.PROCESS_ID IS NULL
        OR B.OPERATION_ID IS NULL
        OR P.OPERATION_ID <> T.OPERATION_ID
    ) AS TRANSACTION_LINK_ERRORS
FROM DUAL;

CREATE OR REPLACE VIEW VW_AN_SYSTEM_INSIGHTS AS
SELECT
    'OPERATIONS' AS CATEGORY,
    CASE
        WHEN TOTAL_OPERATIONS = 0
            THEN 'No business operations have been created.'
        WHEN COMPLETION_PERCENT = 100
            THEN 'All business operations are completed.'
        ELSE TO_CHAR(TOTAL_OPERATIONS - COMPLETED_OPERATIONS)
             || ' business operations are not yet completed.'
    END AS INSIGHT
FROM VW_AN_OPERATION_SUMMARY
UNION ALL
SELECT
    'PROCESSES',
    CASE
        WHEN TOTAL_PROCESSES = 0
            THEN 'No OS processes have been generated.'
        WHEN COMPLETION_PERCENT = 100
            THEN 'All generated processes are terminated.'
        WHEN WAITING_PROCESSES > 0
            THEN TO_CHAR(WAITING_PROCESSES)
                 || ' processes are waiting for resources.'
        ELSE 'Some processes have not yet terminated.'
    END
FROM VW_AN_PROCESS_SUMMARY
UNION ALL
SELECT
    'RESOURCES',
    CASE
        WHEN COUNT(*) = 0 THEN 'No resources are configured.'
        WHEN SUM(CASE WHEN ACCOUNTING_DIFFERENCE <> 0
            THEN 1 ELSE 0 END) > 0
            THEN 'Resource accounting inconsistencies detected.'
        WHEN SUM(CASE WHEN AVAILABLE_UNITS = 0
            AND WAITING_PROCESSES > 0
            THEN 1 ELSE 0 END) > 0
            THEN 'At least one fully occupied resource has waiting requests.'
        ELSE 'Resource accounting is consistent.'
    END
FROM VW_AN_RESOURCE_USAGE
UNION ALL
SELECT
    'TRANSACTIONS',
    CASE
        WHEN TOTAL_TRANSACTIONS = 0
            THEN 'No database transactions have been recorded.'
        WHEN ROLLED_BACK_TRANSACTIONS > 0
            THEN TO_CHAR(ROLLED_BACK_TRANSACTIONS)
                 || ' transactions were rolled back.'
        ELSE 'No transaction rollbacks have been recorded.'
    END
FROM VW_AN_TRANSACTION_SUMMARY;
